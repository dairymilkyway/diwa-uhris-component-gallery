/**
 * Component Registry
 *
 * Single source of truth for every component in the gallery.
 * Powers: homepage grid, sidebar nav, search, related components,
 * breadcrumbs, component counts, and future filters.
 *
 * status:
 *   'complete'     — gallery page exists and is fully built
 *   'wip'          — page exists but is incomplete
 *   'coming-soon'  — planned, no page yet
 */

export type ComponentStatus = 'complete' | 'wip' | 'coming-soon';

export interface ComponentEntry {
  id: string;
  name: string;
  category: string;
  status: ComponentStatus;
  /** null = no route yet (coming soon) */
  route: string | null;
  aliases: string[];
  description: string;
  popular?: boolean;
}

