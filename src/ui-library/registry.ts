/** Look up multiple components by id for the RelatedComponents section */
export function getRelatedComponents(ids: string[]): ComponentEntry[] {
  return ids
    .map((id) => COMPONENT_REGISTRY.find((c) => c.id === id))
    .filter((c): c is ComponentEntry => c !== undefined);
}

/** Get all components grouped by category as a Map */
export function getComponentsByCategory(): Map<GalleryCategory, ComponentEntry[]> {
  const map = new Map<GalleryCategory, ComponentEntry[]>();
  for (const cat of GALLERY_CATEGORIES) {
    map.set(cat, COMPONENT_REGISTRY.filter((c) => c.category === cat));
  }
  return map;
}
